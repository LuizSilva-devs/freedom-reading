export const LANGS = ["pt", "en"];
let current = "pt";

export function detectLang() {
  const nav = (navigator.language || "pt").toLowerCase();
  return nav.startsWith("pt") ? "pt" : "en";
}

export function getLang() { return current; }

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : "pt";
  document.documentElement.lang = current === "pt" ? "pt-BR" : "en";
  applyStatic();
}

export function t(key, vars) {
  let s = DICT[current][key] ?? DICT.pt[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return s;
}

/** Aplica os textos nos elementos estáticos do HTML. */
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.title = "Freadom Reading";
}

export function _keys(lang) { return Object.keys(DICT[lang]); }
